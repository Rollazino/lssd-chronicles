export type TranslationKey = keyof (typeof messages)["cs"];

function getInitialLanguage(): Language {
  const savedLanguage = window.localStorage.getItem("lssd-language");
  return languages.includes(savedLanguage as Language) ? (savedLanguage as Language) : "cs";
}

export function LocalizationProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage);

  useEffect(() => {
    window.localStorage.setItem("lssd-language", language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LocalizationContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key) => messages[language][key] ?? messages.cs[key],
    }),
    [language],
  );

  return <LocalizationContext.Provider value={value}>{children}</LocalizationContext.Provider>;
}
